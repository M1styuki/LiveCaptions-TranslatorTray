//! Development-only metadata probe for a retained, identity-checked test host.
//! No VA clone, thread contexts, object names in output, injection or closure
//! of target resources. Uses the existing Microsoft windows crate definitions.
//! API/lifetime: https://learn.microsoft.com/windows/win32/api/_proc_snap/
use std::{collections::BTreeMap, io, mem::size_of, path::Path};
use windows::{
    Win32::{
        Foundation::{CloseHandle, ERROR_NO_MORE_ITEMS, FILETIME, HANDLE, HLOCAL, LocalFree},
        System::{
            Diagnostics::ProcessSnapshotting::*,
            ProcessStatus::K32GetMappedFileNameW,
            Threading::{
                GetCurrentProcess, GetProcessHandleCount, GetProcessIdOfThread, GetProcessTimes,
                GetThreadDescription, GetThreadTimes, OpenProcess, OpenThread, PROCESS_DUP_HANDLE,
                PROCESS_NAME_WIN32, PROCESS_QUERY_INFORMATION, PROCESS_VM_READ,
                QueryFullProcessImageNameW, THREAD_QUERY_LIMITED_INFORMATION,
            },
        },
    },
    core::PWSTR,
};

struct Process(HANDLE);
impl Drop for Process {
    fn drop(&mut self) {
        // SAFETY: this observer owns exactly this OpenProcess/OpenThread handle.
        let _ = unsafe { CloseHandle(self.0) };
    }
}
struct Snapshot(HPSS);
impl Drop for Snapshot {
    fn drop(&mut self) {
        // SAFETY: PssCaptureSnapshot allocated this snapshot in the observer.
        let _ = unsafe { PssFreeSnapshot(GetCurrentProcess(), self.0) };
    }
}
struct Marker(HPSSWALK);
impl Drop for Marker {
    fn drop(&mut self) {
        // SAFETY: this marker was created here and has no concurrent walker.
        let _ = unsafe { PssWalkMarkerFree(self.0) };
    }
}
fn status(code: u32) -> io::Result<()> {
    if code == 0 {
        Ok(())
    } else {
        Err(io::Error::from_raw_os_error(code as i32))
    }
}
fn time(value: FILETIME) -> u64 {
    (u64::from(value.dwHighDateTime) << 32) | u64::from(value.dwLowDateTime)
}
fn marker() -> io::Result<Marker> {
    let mut result = HPSSWALK::default();
    // SAFETY: output is valid; Windows owns allocation until Marker::drop.
    status(unsafe { PssWalkMarkerCreate(None, &mut result) })?;
    Ok(Marker(result))
}
fn walk<T: Default>(
    snapshot: &Snapshot,
    kind: PSS_WALK_INFORMATION_CLASS,
    marker: &Marker,
) -> io::Result<Option<T>> {
    let mut value = T::default();
    // SAFETY: typed Microsoft structures are writable for their exact size.
    let bytes = unsafe {
        std::slice::from_raw_parts_mut((&mut value as *mut T).cast::<u8>(), size_of::<T>())
    };
    let code = unsafe { PssWalkSnapshot(snapshot.0, kind, marker.0, Some(bytes)) };
    if code == ERROR_NO_MORE_ITEMS.0 {
        return Ok(None);
    }
    status(code)?;
    Ok(Some(value))
}
pub struct Thread {
    pub id: u32,
    pub description: Option<String>,
    pub description_error: Option<String>,
    pub start_address: usize,
    pub module: Option<String>,
}
pub struct Report {
    pub pid: u32,
    pub creation_filetime: u64,
    pub handles_before: u32,
    pub handles_after: u32,
    pub handles: Vec<(usize, String)>,
    pub handle_types: BTreeMap<String, usize>,
    pub threads: Vec<Thread>,
}

pub fn own_handle_count() -> io::Result<u32> {
    let mut value = 0;
    // SAFETY: only query the observer's own process and writable output.
    unsafe { GetProcessHandleCount(GetCurrentProcess(), &mut value) }.map_err(io::Error::other)?;
    Ok(value)
}

/// Fresh-process, self-only diagnostic. Never exports the generated bytes.
pub fn rng_handle_counts(api: &str) -> io::Result<[u32; 3]> {
    use windows::Win32::Security::Cryptography::{
        BCRYPT_USE_SYSTEM_PREFERRED_RNG, BCryptGenRandom, ProcessPrng,
    };
    if !matches!(api, "bcrypt" | "process") {
        return Err(io::Error::other("Unknown RNG diagnostic API"));
    }
    let count = || -> io::Result<u32> {
        let mut value = 0;
        // SAFETY: query the observer itself; output is writable.
        unsafe { GetProcessHandleCount(GetCurrentProcess(), &mut value) }
            .map_err(io::Error::other)?;
        Ok(value)
    };
    let before = count()?;
    let mut bytes = [0_u8; 16];
    let mut generate = || -> io::Result<()> {
        // SAFETY: the only output is the writable 16-byte local buffer.
        unsafe {
            if api == "bcrypt" {
                BCryptGenRandom(None, &mut bytes, BCRYPT_USE_SYSTEM_PREFERRED_RNG)
                    .ok()
                    .map_err(io::Error::other)
            } else if ProcessPrng(&mut bytes).as_bool() {
                Ok(())
            } else {
                Err(io::Error::other("ProcessPrng returned FALSE"))
            }
        }
    };
    generate()?;
    let after_first = count()?;
    for _ in 0..99 {
        generate()?;
    }
    std::thread::sleep(std::time::Duration::from_millis(500));
    Ok([before, after_first, count()?])
}

pub fn inspect(pid: u32, creation_filetime: u64, expected_exe: &Path) -> io::Result<Report> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../target")
        .canonicalize()?;
    let expected = expected_exe.canonicalize()?;
    if !expected.starts_with(&root)
        || expected
            .file_name()
            .is_none_or(|name| name != "LiveCaptionsTray.exe")
    {
        return Err(io::Error::other(
            "Only this project's built test host is allowed",
        ));
    }
    // SAFETY: read/query/duplicate rights only; no VM write/operation or terminate.
    let process = Process(
        unsafe {
            OpenProcess(
                PROCESS_QUERY_INFORMATION | PROCESS_VM_READ | PROCESS_DUP_HANDLE,
                false,
                pid,
            )
        }
        .map_err(io::Error::other)?,
    );
    let mut created = FILETIME::default();
    let mut exited = FILETIME::default();
    let mut kernel = FILETIME::default();
    let mut user = FILETIME::default();
    // SAFETY: retained process and valid output values; never trust PID alone.
    unsafe { GetProcessTimes(process.0, &mut created, &mut exited, &mut kernel, &mut user) }
        .map_err(io::Error::other)?;
    let mut image = vec![0u16; 32768];
    let mut length = image.len() as u32;
    unsafe {
        QueryFullProcessImageNameW(
            process.0,
            PROCESS_NAME_WIN32,
            PWSTR(image.as_mut_ptr()),
            &mut length,
        )
    }
    .map_err(io::Error::other)?;
    let image = std::path::PathBuf::from(String::from_utf16_lossy(&image[..length as usize]))
        .canonicalize()?;
    if time(created) != creation_filetime
        || !image
            .to_string_lossy()
            .eq_ignore_ascii_case(&expected.to_string_lossy())
    {
        return Err(io::Error::other("Test process identity mismatch"));
    }
    let mut before = 0;
    unsafe { GetProcessHandleCount(process.0, &mut before) }.map_err(io::Error::other)?;
    let mut raw = HPSS::default();
    // Handles and thread metadata only. Names are requested for TypeName; actual
    // object names are deliberately never copied into the report.
    let flags = PSS_CAPTURE_HANDLES
        | PSS_CAPTURE_HANDLE_NAME_INFORMATION
        | PSS_CAPTURE_HANDLE_BASIC_INFORMATION
        | PSS_CAPTURE_HANDLE_TYPE_SPECIFIC_INFORMATION
        | PSS_CAPTURE_THREADS;
    status(unsafe { PssCaptureSnapshot(process.0, flags, None, &mut raw) })?;
    let snapshot = Snapshot(raw);
    let handle_marker = marker()?;
    let mut handles = Vec::new();
    let mut types = BTreeMap::new();
    while let Some(entry) = walk::<PSS_HANDLE_ENTRY>(&snapshot, PSS_WALK_HANDLES, &handle_marker)? {
        let name = if !entry.TypeName.is_null() && entry.TypeNameLength > 0 {
            // SAFETY: Windows promises this byte-counted UTF-16 buffer is live
            // until the marker is freed. Copy before advancing/freeing it.
            String::from_utf16_lossy(unsafe {
                std::slice::from_raw_parts(entry.TypeName.0, entry.TypeNameLength as usize / 2)
            })
            .trim_end_matches('\0')
            .to_owned()
        } else {
            format!("object-type-{}", entry.ObjectType.0)
        };
        *types.entry(name.clone()).or_insert(0) += 1;
        handles.push((entry.Handle.0 as usize, name));
    }
    let thread_marker = marker()?;
    let mut threads = Vec::new();
    while let Some(entry) = walk::<PSS_THREAD_ENTRY>(&snapshot, PSS_WALK_THREADS, &thread_marker)? {
        let description = (|| -> io::Result<String> {
            let thread = Process(
                unsafe { OpenThread(THREAD_QUERY_LIMITED_INFORMATION, false, entry.ThreadId) }
                    .map_err(io::Error::other)?,
            );
            let mut c = FILETIME::default();
            unsafe { GetThreadTimes(thread.0, &mut c, &mut exited, &mut kernel, &mut user) }
                .map_err(io::Error::other)?;
            if unsafe { GetProcessIdOfThread(thread.0) } != pid || time(c) != time(entry.CreateTime)
            {
                return Err(io::Error::other("Thread identity changed after snapshot"));
            }
            let text = unsafe { GetThreadDescription(thread.0) }.map_err(io::Error::other)?;
            let result = if text.is_null() {
                Ok(String::new())
            } else {
                unsafe { text.to_string() }.map_err(io::Error::other)
            };
            // SAFETY: GetThreadDescription explicitly gives caller a LocalFree buffer.
            if !text.is_null() {
                let _ = unsafe { LocalFree(Some(HLOCAL(text.0.cast()))) };
            }
            result
        })();
        let mut module = vec![0u16; 32768];
        let size = unsafe { K32GetMappedFileNameW(process.0, entry.Win32StartAddress, &mut module) }
            as usize;
        let module = (size > 0).then(|| {
            String::from_utf16_lossy(&module[..size])
                .rsplit('\\')
                .next()
                .unwrap()
                .to_owned()
        });
        let (description, error) = match description {
            Ok(value) => (Some(value), None),
            Err(error) => (None, Some(error.to_string())),
        };
        threads.push(Thread {
            id: entry.ThreadId,
            description,
            description_error: error,
            start_address: entry.Win32StartAddress as usize,
            module,
        });
    }
    let mut after = 0;
    unsafe { GetProcessHandleCount(process.0, &mut after) }.map_err(io::Error::other)?;
    Ok(Report {
        pid,
        creation_filetime,
        handles_before: before,
        handles_after: after,
        handles,
        handle_types: types,
        threads,
    })
}
